// AI対話で、選択肢のどれも当てはまらないときに使う回答。
//
// 「得意な領域は何ですか」のような質問に対して、選択肢を見ても
// どれが当てはまるか分からなかった、というフィードバックを受けて追加した。
// 逃げ道がないと、当てはまらない選択肢を無理に選ぶことになり、
// その答えがそのままスキルマップの採点に使われてしまう。
//
// UI(選択肢の下のボタン)とプロンプト(この回答が来たときの扱い)の
// 両方から参照するため、ここに1箇所だけ定義する。
export const NO_MATCHING_OPTION_ANSWER = "この中に当てはまるものがない";

// 採点時の扱い。「経験がない」ではなく「情報が得られなかった」として扱う。
export const NO_MATCHING_OPTION_NOTE = `回答が「${NO_MATCHING_OPTION_ANSWER}」だった質問は、
選択肢が本人の状況に合わなかっただけです。その軸に経験がないという意味ではないので、
その回答を根拠に点数を下げないでください(情報が得られなかった軸として扱い、
他の申告内容や経歴から推定してください)。`;
